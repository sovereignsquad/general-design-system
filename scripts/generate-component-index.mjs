// Issue 626 Phase 2 — the COMPLETE element list, derived (Rule 14), never curated.
//
// The owner's requirement verbatim: "a complete element list with all examples and use cases;
// nothing the system can do may be hidden." A hand-maintained index is a hidden-component
// generator: the first component someone forgets to add is invisible again. So the index is
// DERIVED from the same census the parity gate reads — every public PascalCase component
// export across the packages — joined with the pattern registry (which entry is each
// component's canonical home) and the reviewed exemption allowlist (why a helper has no page
// of its own). Every one of the census's components appears: registered ones link to their
// home; exempt ones state their reason in full view. Nothing is invisible, including the
// decision to not give something a page.
//
// Output: apps/playground/src/generated-component-index.ts (committed; drift fails the
// clean-tree preflight and the parity gate's own --check).
//
// Run: node scripts/generate-component-index.mjs [--check]

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { collectPublicComponents } from './lib/component-census.mjs';

const root = process.cwd();
const registryPath = resolve(root, 'apps/playground/src/pattern-registry.ts');
const exemptionsPath = resolve(root, 'boundary/component-catalog-exemptions.json');
const outPath = resolve(root, 'apps/playground/src/generated-component-index.ts');
const check = process.argv.includes('--check');

const census = [...collectPublicComponents()].sort((a, b) => a.localeCompare(b));

// component -> the registry entries that claim it as sourceComponent evidence.
const registrySource = readFileSync(registryPath, 'utf8');
const entries = [...registrySource.matchAll(
  /id: '([^']+)',[\s\S]{0,700}?family: '([^']+)',[\s\S]{0,400}?section: '([^']+)',[\s\S]{0,700}?sourceComponent: '([^']+)'/g,
)];
const homes = new Map();
for (const [, id, family, section, source] of entries) {
  for (const token of source.split(/[\/,\s]+/)) {
    const name = token.trim();
    if (!name) continue;
    (homes.get(name) ?? homes.set(name, []).get(name)).push({ id, family, section });
  }
}

const exemptions = JSON.parse(readFileSync(exemptionsPath, 'utf8')).exemptions ?? {};

const rows = census.map((name) => {
  const registered = homes.get(name) ?? [];
  if (registered.length > 0) {
    // The FIRST registering entry is the canonical home; further entries are compositions
    // that also exercise it. One canonical page each — the Phase 2 gate's claim.
    const [home, ...also] = registered;
    return { name, status: 'registered', home, alsoAppearsIn: also.map((entry) => entry.id) };
  }
  if (name in exemptions) {
    return { name, status: 'exempt', reason: exemptions[name] };
  }
  return { name, status: 'unaccounted' };
});

const unaccounted = rows.filter((row) => row.status === 'unaccounted');
if (unaccounted.length > 0) {
  // The parity gate fails these too; failing here as well keeps the generator honest when
  // run standalone.
  console.error(`Component index: ${unaccounted.length} component(s) neither registered nor exempted:`);
  for (const row of unaccounted) console.error(`- ${row.name}`);
  process.exit(1);
}

const output = `// Generated by scripts/generate-component-index.mjs — the complete element list,\n`
  + `// derived from the component census + pattern registry + reviewed exemptions (issue 626).\n`
  + `// Do not edit; regenerate via artifacts:refresh.\n\n`
  + `export interface GdsComponentIndexRow {\n`
  + `  name: string;\n`
  + `  status: 'registered' | 'exempt';\n`
  + `  home?: { id: string; family: string; section: string };\n`
  + `  alsoAppearsIn?: string[];\n`
  + `  reason?: string;\n`
  + `}\n\n`
  + `export const gdsComponentIndex: GdsComponentIndexRow[] = ${JSON.stringify(rows, null, 2)};\n`;

if (check) {
  const current = existsSync(outPath) ? readFileSync(outPath, 'utf8') : '';
  if (current !== output) {
    console.error('generated-component-index.ts has drifted from the census. Run `node scripts/generate-component-index.mjs` and commit.');
    process.exit(1);
  }
  console.log(`Component index is current: ${rows.length} components (${rows.filter((r) => r.status === 'registered').length} registered, ${rows.filter((r) => r.status === 'exempt').length} exempt).`);
} else {
  writeFileSync(outPath, output);
  console.log(`Component index written: ${rows.length} components (${rows.filter((r) => r.status === 'registered').length} registered, ${rows.filter((r) => r.status === 'exempt').length} exempt).`);
}
