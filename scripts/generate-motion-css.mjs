// Single source of truth for the nine motion values: `gdsMotionDurations` / `gdsMotionEasings`
// in packages/gds-theme/src/motion.ts.
//
// Regenerates the styles.css blocks between markers via `createGdsMotionCssVariables()`;
// drift-checked against motion.ts.

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = process.cwd();
const stylesPath = resolve(root, 'packages/gds-theme/styles.css');
const START = '/* gds:motion-scale:start — generated by scripts/generate-motion-css.mjs, do not edit by hand */';
const END = '/* gds:motion-scale:end */';
const REDUCED_START = '/* gds:motion-reduced:start — generated by scripts/generate-motion-css.mjs, do not edit by hand */';
const REDUCED_END = '/* gds:motion-reduced:end */';

const { createGdsMotionCssVariables } = await import(resolve(root, 'packages/gds-theme/dist/index.mjs'));

const render = (vars, indent) =>
  Object.entries(vars)
    .map(([name, value]) => `${indent}${name}: ${value};`)
    .join('\n');

function replaceBlock(css, start, end, body) {
  const from = css.indexOf(start);
  const to = css.indexOf(end);
  if (from === -1 || to === -1) {
    console.error(`FAIL markers missing in styles.css: ${start.slice(0, 40)}…`);
    process.exit(1);
  }
  return `${css.slice(0, from + start.length)}\n${body}\n${css.slice(to)}`;
}

const current = readFileSync(stylesPath, 'utf8');
let next = replaceBlock(current, START, END, render(createGdsMotionCssVariables('system'), '  '));
// Reduced-motion block uses the same emitter under its no-motion policy, so it cannot
// diverge from the normal block's definition of "reduced".
next = replaceBlock(next, REDUCED_START, REDUCED_END, render(createGdsMotionCssVariables('no-motion'), '    '));

if (process.argv.includes('--check')) {
  if (next !== current) {
    console.error('FAIL packages/gds-theme/styles.css motion blocks have drifted from motion.ts.');
    console.error('     Run `npm run tokens:motion-css` and commit the result.');
    process.exit(1);
  }
  console.log('Motion CSS drift check passed: styles.css matches gdsMotionDurations/gdsMotionEasings.');
  process.exit(0);
}

writeFileSync(stylesPath, next);
console.log('Motion CSS blocks regenerated from motion.ts.');
