// Issue 608 — derive `coverageStatus` instead of writing it.
//
// All 113 registry entries carried the same hand-typed value. A field with one observed value
// cannot be observed to be wrong, which is how seven entries claimed a live proof while their
// cards rendered "No interactive demo renders here" (issue 600).
//
// `verify:pattern-live-proof` closed the false-positive direction: nothing can now CLAIM a live
// proof without one. It does not make the claim derived — a correct claim is still an authored
// one, and the three other enum values remained unreachable because nobody ever typed them.
//
// This closes the rest. Whether a pattern has a live proof is something the system can be
// asked — does `renderEntryDemo()` have a case for this id, or does `PatternEntryCard`
// special-case it — so it is computed here and read by the registry rather than maintained by
// hand (Rule 14: a checkable claim is computed, never retyped).
//
// Why a GENERATED FILE rather than computing it in the registry at runtime: `pattern-pages.tsx`
// imports `pattern-registry.ts`, so the registry cannot import the pages back without a cycle.
// The same reason `generated-component-census.ts` exists, and the same `--check` drift guard.
//
// Run by `npm run artifacts:refresh`; drift-checked by `npm run verify:pattern-coverage`.

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = process.cwd();
const check = process.argv.includes('--check');

const pagesPath = resolve(root, 'apps/playground/src/pattern-pages.tsx');
const outputPath = resolve(root, 'apps/playground/src/generated-pattern-coverage.ts');

const pages = readFileSync(pagesPath, 'utf8');

// The two ways a card can render a proof, which is exactly what verify:pattern-live-proof reads.
const demoCases = [...pages.matchAll(/case '([^']+)':/g)].map((match) => match[1]);
const specialCased = [...pages.matchAll(/entry\.id === '([^']+)'/g)].map((match) => match[1]);
const proven = [...new Set([...demoCases, ...specialCased])].sort();

if (proven.length === 0) {
  console.error('Parsed 0 proven pattern ids from pattern-pages.tsx — refusing to write a file that would demote every entry.');
  process.exit(1);
}

const contents = `// GENERATED by scripts/generate-pattern-coverage.mjs — do not edit.
//
// Pattern ids whose card renders a real proof: a \`case\` in \`renderEntryDemo()\` or an explicit
// \`PatternEntryCard\` branch. \`pattern-registry.ts\` derives \`coverageStatus\` from this, so the
// status cannot disagree with what the page actually renders (issue 608).
export const provenPatternIds: readonly string[] = ${JSON.stringify(proven, null, 2)} as const;
`;

if (check) {
  const current = readFileSync(outputPath, 'utf8');
  if (current !== contents) {
    console.error('Pattern coverage drift: apps/playground/src/generated-pattern-coverage.ts is stale.');
    console.error('Run `npm run artifacts:refresh` and commit the result.');
    process.exit(1);
  }
  console.log(`Pattern coverage verification passed (${proven.length} patterns render a proof).`);
} else {
  writeFileSync(outputPath, contents);
  console.log(`Wrote ${proven.length} proven pattern ids to apps/playground/src/generated-pattern-coverage.ts`);
}
