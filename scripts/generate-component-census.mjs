// Issue 605 — publishes the public-component count to the reference site.
//
// The site stated "250+ governed, accessible React components". True at the time (289) and
// written by hand, so it drifts silently in both directions: it understates the system today,
// and becomes a false promise the moment the count drops. Under Rule 14 a checkable claim is
// computed, not written — and the fix for "the page cannot compute it at runtime" is to give
// the page the number, not to delete the sentence.
//
// The count comes from `collectPublicComponents()`, the SAME function
// `verify-component-catalog-parity` enforces against, so the number on the page and the number
// the gate checks cannot disagree.
//
// `--check` fails when the committed file is stale, exactly as `verify:motion-css` does for
// the motion scale.

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { collectPublicComponents } from './lib/component-census.mjs';

const ROOT = new URL('..', import.meta.url).pathname;
const OUT = resolve(ROOT, 'apps/playground/src/generated-component-census.ts');
const check = process.argv.includes('--check');

const components = collectPublicComponents();
if (components.size === 0) {
  console.error('FAIL The census found zero components. Emitting that would put a false 0 on the site.');
  process.exit(1);
}

const contents = `// Generated by scripts/generate-component-census.mjs. Do not edit by hand.
//
// The count the reference site quotes, produced by the same function
// verify-component-catalog-parity enforces against — so the page and the gate cannot disagree.
// Regenerate with \`npm run tokens:component-census\`; \`--check\` fails on drift.

/** Public UI components exported by the GDS packages. */
export const GDS_PUBLIC_COMPONENT_COUNT = ${components.size};
`;

if (check) {
  const current = (() => { try { return readFileSync(OUT, 'utf8'); } catch { return ''; } })();
  if (current !== contents) {
    console.error('FAIL apps/playground/src/generated-component-census.ts is stale relative to the packages.');
    console.error('     Run `npm run tokens:component-census` and commit the result.');
    process.exit(1);
  }
  console.log(`Component census check passed: the site quotes ${components.size} public UI components.`);
} else {
  writeFileSync(OUT, contents);
  console.log(`Component census written: ${components.size} public UI components.`);
}
