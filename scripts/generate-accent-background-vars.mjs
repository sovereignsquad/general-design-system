// Generates the accent-classed CSS custom-property name list from gds-theme's
// ACCENT_ROLES (issue #644), so no consumer of the list can hand-duplicate the
// classification. Two consumers read the identical generated list: gds-eslint-config's
// no-accent-as-background rule (issue #647) and gds-compliance's design-rule scan
// (issue #652) -- one generation, two output files, so the two packages' lists cannot
// drift apart independently.
//
// Output: packages/gds-eslint-config/generated-accent-background-vars.js
//         packages/gds-compliance/generated-accent-background-vars.js
// Run: node scripts/generate-accent-background-vars.mjs   (wired into artifacts:refresh)
// `--check` fails when either committed file is stale.

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const OUT_PATHS = [
  resolve(ROOT, 'packages/gds-eslint-config/generated-accent-background-vars.js'),
  resolve(ROOT, 'packages/gds-compliance/generated-accent-background-vars.js'),
];
const check = process.argv.includes('--check');

const { ACCENT_ROLES } = await import(resolve(ROOT, 'packages/gds-theme/dist/index.mjs'));

if (!ACCENT_ROLES || ACCENT_ROLES.length === 0) {
  console.error('FAIL ACCENT_ROLES (packages/gds-theme, issue #644) resolved empty -- refusing to emit an empty variable list.');
  process.exit(1);
}

// Mirrors semantic-token-source.ts's cssVarName(role, 'light') exactly: a role with a
// dot (e.g. "brand.accent") becomes one hyphenated segment ("--gds-brand-accent").
const variables = ACCENT_ROLES.map((role) => `--gds-${role.replace('.', '-')}`).sort();

const contents = `// Generated by scripts/generate-accent-background-vars.mjs. Do not edit by hand.
//
// The accent-classed CSS custom-property names (issue #644's ACCENT_ROLES, mapped to
// their --gds-* variable names), shared verbatim by gds-eslint-config's
// no-accent-as-background rule (issue #647) and gds-compliance's design-rule scan
// (issue #652). Regenerate with \`npm run generate:accent-background-vars\`; \`--check\`
// fails on drift.

export const ACCENT_BACKGROUND_VARIABLES = ${JSON.stringify(variables, null, 2)};
`;

if (check) {
  let stale = false;
  for (const out of OUT_PATHS) {
    const current = (() => { try { return readFileSync(out, 'utf8'); } catch { return ''; } })();
    if (current !== contents) {
      console.error(`FAIL ${out.slice(ROOT.length)} is stale relative to ACCENT_ROLES.`);
      stale = true;
    }
  }
  if (stale) {
    console.error('     Run `npm run generate:accent-background-vars` and commit the result.');
    process.exit(1);
  }
  console.log(`Accent-background variable list check passed: ${variables.length} accent-classed CSS variables (2 files).`);
} else {
  for (const out of OUT_PATHS) writeFileSync(out, contents);
  console.log(`Accent-background variable list written: ${variables.length} accent-classed CSS variables (2 files).`);
}
