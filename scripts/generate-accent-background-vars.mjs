// Generates the accent-classed CSS custom-property name list `no-accent-as-background`
// (packages/gds-eslint-config) checks source against, from gds-theme's ACCENT_ROLES
// (issue #644) -- so the rule can never hand-duplicate the classification.
//
// Output: packages/gds-eslint-config/generated-accent-background-vars.js
// Run: node scripts/generate-accent-background-vars.mjs   (wired into artifacts:refresh)
// `--check` fails when the committed file is stale.

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const OUT = resolve(ROOT, 'packages/gds-eslint-config/generated-accent-background-vars.js');
const check = process.argv.includes('--check');

const { ACCENT_ROLES } = await import(resolve(ROOT, 'packages/gds-theme/dist/index.mjs'));

if (!ACCENT_ROLES || ACCENT_ROLES.length === 0) {
  console.error('FAIL ACCENT_ROLES (packages/gds-theme, issue #644) resolved empty -- refusing to emit an empty variable list.');
  process.exit(1);
}

// Mirrors semantic-token-source.ts's cssVarName(role, 'light') exactly: a role with a
// dot (e.g. "brand.accent") becomes one hyphenated segment ("--gds-brand-accent").
const variables = ACCENT_ROLES.map((role) => `--gds-${role.replace('.', '-')}`).sort();

const contents = `// Generated by scripts/generate-accent-background-vars.mjs. Do not edit by hand.
//
// The accent-classed CSS custom-property names (issue #644's ACCENT_ROLES, mapped to
// their --gds-* variable names) no-accent-as-background flags as a background fill.
// Regenerate with \`npm run generate:accent-background-vars\`; \`--check\` fails on drift.

export const ACCENT_BACKGROUND_VARIABLES = ${JSON.stringify(variables, null, 2)};
`;

if (check) {
  const current = (() => { try { return readFileSync(OUT, 'utf8'); } catch { return ''; } })();
  if (current !== contents) {
    console.error('FAIL packages/gds-eslint-config/generated-accent-background-vars.js is stale relative to ACCENT_ROLES.');
    console.error('     Run `npm run generate:accent-background-vars` and commit the result.');
    process.exit(1);
  }
  console.log(`Accent-background variable list check passed: ${variables.length} accent-classed CSS variables.`);
} else {
  writeFileSync(OUT, contents);
  console.log(`Accent-background variable list written: ${variables.length} accent-classed CSS variables.`);
}
