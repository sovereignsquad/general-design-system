// Copies issue 649/#650's audit/design-rule-coverage.json into a typed, generated TS
// module gds-core can import directly -- mirrors generate-component-census.mjs's existing
// "read committed audit JSON, emit typed TS" pattern. A preset absent from the artifact
// (not yet swept) is simply absent from the generated Record; GdsDesignRuleProfilePanel
// renders GdsChart's own empty state for it rather than a fabricated zero.
//
// Output: packages/gds-core/src/generated-design-rule-coverage.ts
// Run: node scripts/generate-design-rule-coverage-module.mjs   (wired into artifacts:refresh)
// `--check` fails when the committed file is stale.

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const SOURCE = resolve(ROOT, 'audit/design-rule-coverage.json');
const OUT = resolve(ROOT, 'packages/gds-core/src/generated-design-rule-coverage.ts');
const check = process.argv.includes('--check');

const source = JSON.parse(readFileSync(SOURCE, 'utf8'));
const presetIds = Object.keys(source.presets ?? {});

if (presetIds.length === 0) {
  console.error('FAIL audit/design-rule-coverage.json has zero presets -- refusing to emit an empty coverage module.');
  process.exit(1);
}

const entries = presetIds
  .sort()
  .map((id) => {
    const p = source.presets[id];
    return `  '${id}': { dominant: ${p.dominant}, secondary: ${p.secondary}, accent: ${p.accent}, unclassified: ${p.unclassified} },`;
  })
  .join('\n');

const contents = `// Generated by scripts/generate-design-rule-coverage-module.mjs. Do not edit by hand.
//
// A typed copy of issue 649/#650's audit/design-rule-coverage.json -- the real,
// measured rendered color-proportion percentages per preset, for GdsDesignRuleProfilePanel
// (issue 651) to import directly with zero runtime fetch cost. Regenerate with
// \`npm run generate:design-rule-coverage-module\`; \`--check\` fails on drift.
//
// A preset absent here has not yet been swept by issue 649's audit; consumers must
// handle that as a real "no data yet" case, never assume every GdsThemePresetId is present.

import type { GdsThemePresetId } from '@sovereignsquad/gds-theme';

/** One preset's measured rendered color-proportion percentages (issue 649/#650). */
export interface GdsDesignRuleCoverageEntry {
  dominant: number;
  secondary: number;
  accent: number;
  unclassified: number;
}

export const designRuleCoverageByPreset: Partial<Record<GdsThemePresetId, GdsDesignRuleCoverageEntry>> = {
${entries}
};
`;

if (check) {
  const current = (() => { try { return readFileSync(OUT, 'utf8'); } catch { return ''; } })();
  if (current !== contents) {
    console.error('FAIL packages/gds-core/src/generated-design-rule-coverage.ts is stale relative to audit/design-rule-coverage.json.');
    console.error('     Run `npm run generate:design-rule-coverage-module` and commit the result.');
    process.exit(1);
  }
  console.log(`Design-rule coverage module check passed: ${presetIds.length} preset(s).`);
} else {
  writeFileSync(OUT, contents);
  console.log(`Design-rule coverage module written: ${presetIds.length} preset(s).`);
}
