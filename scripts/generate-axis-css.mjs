// Default axis tokens for lanes without a preset runtime (gdsTheme, gdsDarkPublicTheme,
// createPublicBrandTheme): the styles.css `:root` block between the gds:axis-defaults markers,
// written from the built package's resolveGdsAxisTokens(undefined) (the GDS_DEFAULT_* axes).
// `--gds-focus-ring` is added from the `default` preset's emitted light/dark values, because the
// reaction axis's `--gds-focus-ring-color` resolves through it.
// Plain `:root` keeps the block below every preset-runtime, GdsProvider and subtree declaration.
// --check fails when the block drifts from the resolver.

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = process.cwd();
const stylesPath = resolve(root, 'packages/gds-theme/styles.css');
const START = '/* gds:axis-defaults:start — generated by scripts/generate-axis-css.mjs, do not edit by hand */';
const END = '/* gds:axis-defaults:end */';

const theme = await import(resolve(root, 'packages/gds-theme/dist/index.mjs'));
const light = theme.resolveGdsAxisTokens(undefined, 'theme', 'light');
const dark = theme.resolveGdsAxisTokens(undefined, 'theme', 'dark');

const failures = [];
for (const name of new Set([...Object.keys(light), ...Object.keys(dark)])) {
  if (light[name] !== dark[name]) failures.push(`${name} differs between light and dark; the :root block cannot express it.`);
}
const focusLight = theme.getGdsVibeThemeCssVariables('default', 'light')['--gds-focus-ring'];
const focusDark = theme.getGdsVibeThemeCssVariables('default', 'dark')['--gds-focus-ring'];
if (!focusLight || !focusDark) failures.push('The default preset emits no --gds-focus-ring.');
if (failures.length > 0) {
  for (const failure of failures) console.error(`FAIL ${failure}`);
  process.exit(1);
}

const declarations = {
  ...light,
  '--gds-focus-ring': focusLight === focusDark ? focusLight : `light-dark(${focusLight}, ${focusDark})`,
};
const body = [':root {', ...Object.entries(declarations).map(([name, value]) => `  ${name}: ${value};`), '}'].join('\n');

const current = readFileSync(stylesPath, 'utf8');
const from = current.indexOf(START);
const to = current.indexOf(END);
if (from === -1 || to === -1 || to < from) {
  console.error('FAIL packages/gds-theme/styles.css has no gds:axis-defaults markers.');
  process.exit(1);
}
const next = `${current.slice(0, from + START.length)}\n${body}\n${current.slice(to)}`;

if (process.argv.includes('--check')) {
  if (next !== current) {
    console.error('FAIL packages/gds-theme/styles.css axis-defaults block has drifted from resolveGdsAxisTokens.');
    console.error('     Run `npm run artifacts:refresh` and commit the result.');
    process.exit(1);
  }
  console.log(`Axis CSS drift check passed: styles.css declares the ${Object.keys(declarations).length} default axis tokens.`);
  process.exit(0);
}

writeFileSync(stylesPath, next);
console.log(`Axis defaults block regenerated: ${Object.keys(declarations).length} declarations.`);
