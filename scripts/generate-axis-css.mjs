// Default axis tokens for lanes without a preset runtime (gdsTheme, gdsDarkPublicTheme,
// createPublicBrandTheme): the styles.css `:root` block between the gds:axis-defaults markers,
// written from the built package's resolveGdsAxisTokens(undefined) (the GDS_DEFAULT_* axes).
// `--gds-focus-ring` is added from the `default` preset's emitted light/dark values, because the
// reaction axis's `--gds-focus-ring-color` resolves through it.
// A second block (gds:badge-defaults) declares the `default` preset's badge roles, each a
// contrast-checked background/foreground pair (#968).
// The badge, brand/state (gds:brand-defaults) and chart blocks come from getGdsDefaultLaneCssVariables():
// the `default` preset's roles with brand primary and state info on its muted text grey (#968).
// A further block (gds:chart-defaults) declares the `default` preset's chart colour roles and the
// scheme-independent area-gradient opacity stops (GDS_CHART_AREA_OPACITY) (#954).
// Plain `:root` keeps the blocks below every preset-runtime, GdsProvider and subtree declaration.
// --check fails when any block drifts from its source.

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = process.cwd();
const stylesPath = resolve(root, 'packages/gds-theme/styles.css');
const START = '/* gds:axis-defaults:start — generated by scripts/generate-axis-css.mjs, do not edit by hand */';
const END = '/* gds:axis-defaults:end */';
const BADGE_START = '/* gds:badge-defaults:start — generated by scripts/generate-axis-css.mjs, do not edit by hand */';
const BADGE_END = '/* gds:badge-defaults:end */';
const BRAND_START = '/* gds:brand-defaults:start — generated by scripts/generate-axis-css.mjs, do not edit by hand */';
const BRAND_END = '/* gds:brand-defaults:end */';
const BRAND_ROLES = [
  '--gds-brand-primary', '--gds-brand-primary-fg',
  '--gds-brand-accent', '--gds-brand-accent-fg',
  '--gds-brand-accent-action', '--gds-brand-accent-action-fg',
  '--gds-state-success', '--gds-state-warning', '--gds-state-danger', '--gds-state-info',
  '--gds-bg-sidebar', '--gds-nav-active-bg', '--gds-nav-active-fg', '--gds-nav-active-indicator', '--gds-nav-hover-bg',
  '--gds-bg-raised', '--gds-border-subtle', '--gds-border-strong',
  '--gds-message-self-bg', '--gds-message-self-fg', '--gds-message-other-bg', '--gds-message-other-fg',
];
const CHART_START = '/* gds:chart-defaults:start — generated by scripts/generate-axis-css.mjs, do not edit by hand */';
const CHART_END = '/* gds:chart-defaults:end */';

const theme = await import(resolve(root, 'packages/gds-theme/dist/index.mjs'));
const light = theme.resolveGdsAxisTokens(undefined, 'theme', 'light');
const dark = theme.resolveGdsAxisTokens(undefined, 'theme', 'dark');

const failures = [];
for (const name of new Set([...Object.keys(light), ...Object.keys(dark)])) {
  if (light[name] !== dark[name]) failures.push(`${name} differs between light and dark; the :root block cannot express it.`);
}
// Lanes without a preset get the default-lane roles: the `default` preset's values with brand
// primary and state info on its muted grey, and the pairs re-derived from that.
const lane = theme.getGdsDefaultLaneCssVariables();
const scheme = (dark) => Object.fromEntries(
  Object.keys(lane).filter((name) => !name.endsWith('-dark')).map((name) => [name, dark ? lane[`${name}-dark`] ?? lane[name] : lane[name]]),
);
const defaultLight = scheme(false);
const defaultDark = scheme(true);
const focusLight = defaultLight['--gds-focus-ring'];
const focusDark = defaultDark['--gds-focus-ring'];
const schemePair = (lightValue, darkValue) => (lightValue === darkValue ? lightValue : `light-dark(${lightValue}, ${darkValue})`);
const badgeNames = Object.keys(defaultLight).filter((name) => /^--gds-badge-/.test(name) && !name.endsWith('-dark'));
for (const name of badgeNames) {
  if (!defaultDark[name]) failures.push(`The default preset emits no dark value for ${name}.`);
}
if (badgeNames.length === 0) failures.push('The default preset emits no --gds-badge-* roles.');
for (const name of BRAND_ROLES) {
  if (!defaultLight[name] || !defaultDark[name]) failures.push(`The default lane emits no light or dark value for ${name}.`);
}
const chartNames = Object.keys(defaultLight).filter((name) => /^--gds-chart-/.test(name) && !name.endsWith('-dark'));
for (const name of chartNames) {
  if (!defaultDark[name]) failures.push(`The default preset emits no dark value for ${name}.`);
}
if (chartNames.length === 0) failures.push('The default preset emits no --gds-chart-* roles.');
if (!focusLight || !focusDark) failures.push('The default preset emits no --gds-focus-ring.');
if (failures.length > 0) {
  for (const failure of failures) console.error(`FAIL ${failure}`);
  process.exit(1);
}

const declarations = {
  ...light,
  '--gds-focus-ring': schemePair(focusLight, focusDark),
};
const badgeDeclarations = Object.fromEntries(badgeNames.map((name) => [name, schemePair(defaultLight[name], defaultDark[name])]));
const brandDeclarations = Object.fromEntries(BRAND_ROLES.map((name) => [name, schemePair(defaultLight[name], defaultDark[name])]));
const chartDeclarations = Object.fromEntries(chartNames.map((name) => [name, schemePair(defaultLight[name], defaultDark[name])]));
chartDeclarations['--gds-chart-area-opacity-start'] = theme.GDS_CHART_AREA_OPACITY.start;
chartDeclarations['--gds-chart-area-opacity-end'] = theme.GDS_CHART_AREA_OPACITY.end;
const rule = (decls) => [':root {', ...Object.entries(decls).map(([name, value]) => `  ${name}: ${value};`), '}'].join('\n');

function replaceBlock(css, start, end, body) {
  const from = css.indexOf(start);
  const to = css.indexOf(end);
  if (from === -1 || to === -1 || to < from) {
    console.error(`FAIL packages/gds-theme/styles.css has no ${start.slice(3, 30)} markers.`);
    process.exit(1);
  }
  return `${css.slice(0, from + start.length)}\n${body}\n${css.slice(to)}`;
}

const current = readFileSync(stylesPath, 'utf8');
let next = replaceBlock(current, START, END, rule(declarations));
next = replaceBlock(next, BADGE_START, BADGE_END, rule(badgeDeclarations));
next = replaceBlock(next, BRAND_START, BRAND_END, rule(brandDeclarations));
next = replaceBlock(next, CHART_START, CHART_END, rule(chartDeclarations));
const total = Object.keys(declarations).length + badgeNames.length + BRAND_ROLES.length + Object.keys(chartDeclarations).length;

if (process.argv.includes('--check')) {
  if (next !== current) {
    console.error('FAIL packages/gds-theme/styles.css axis-defaults, badge-defaults, brand-defaults or chart-defaults block has drifted from its source.');
    console.error('     Run `npm run artifacts:refresh` and commit the result.');
    process.exit(1);
  }
  console.log(`Axis CSS drift check passed: styles.css declares ${Object.keys(declarations).length} default axis tokens, ${badgeNames.length} badge roles, ${BRAND_ROLES.length} brand and state roles and ${Object.keys(chartDeclarations).length} chart roles.`);
  process.exit(0);
}

writeFileSync(stylesPath, next);
console.log(`Axis, badge, brand and chart defaults regenerated: ${total} declarations.`);
